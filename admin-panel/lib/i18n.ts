const dictionaries = { en, sv, fi };

export async function getLocale(): Promise<Locale> {
  const value = (await cookies()).get(LOCALE_COOKIE)?.value;
  if (value === "sv" || value === "fi" || value === "en") return value;
  return "en";
}

export async function getTheme(): Promise<Theme> {
  const value = (await cookies()).get(THEME_COOKIE)?.value;
  return value === "light" ? "light" : "dark";
}

export function t(locale: Locale, path: string, vars?: Record<string, string>): string {
  const read = (loc: Locale) => {
    const parts = path.split(".");
    let node: unknown = dictionaries[loc];
    for (const part of parts) {
      if (!node || typeof node !== "object") return undefined;
      node = (node as Record<string, unknown>)[part];
    }
    return typeof node === "string" ? node : undefined;
  };
  let text = read(locale) ?? read("en") ?? path;
  if (vars) {
    for (const [key, value] of Object.entries(vars)) {
      text = text.replaceAll(`{${key}}`, value);
    }
  }
  return text;
}
